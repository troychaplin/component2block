import type { C2bConfig, TokenGroup } from '../types.js';
import { CATEGORY_REGISTRY, CATEGORY_ORDER, DEFAULT_FLUID, camelToKebab } from '../types.js';
import { buildFluidClamp } from './fluid.js';

/**
 * Generate `_variables.scss` content. Only emits categories listed in
 * `config.scssVars`, iterated in registry order so the file stays grouped
 * consistently. Returns `null` when `scssVars` is empty — the caller should
 * skip writing the file.
 */
export function generateTokensScss(config: C2bConfig): string | null {
  const scssVars = config.scssVars ?? [];
  if (scssVars.length === 0) return null;

  const selected = new Set(scssVars);
  const lines: string[] = [
    '// Auto-generated by component2block — do not edit manually',
  ];

  for (const category of CATEGORY_ORDER) {
    if (!selected.has(category)) continue;
    const group = config.tokens[category];
    if (!group) continue;

    const def = CATEGORY_REGISTRY[category];

    lines.push('');
    lines.push(`// ${def.label}`);

    for (const [key, entry] of Object.entries(group)) {
      const cssKey = def.directMap ? camelToKebab(key) : key;
      const varName = `$${config.prefix}-${def.cssSegment}-${cssKey}`;
      const clampValue = entry.fluid ? buildFluidClamp(entry, config.fluid ?? DEFAULT_FLUID) : null;
      lines.push(`${varName}: ${clampValue ?? entry.value};`);
    }
  }

  if (selected.has('viewport')) {
    lines.push(...buildViewportMixins(config.prefix, config.tokens.viewport));
  }

  lines.push('');

  return lines.join('\n');
}

/**
 * Build the `@mixin` blocks wrapping the viewport breakpoints as media queries.
 *
 * The breakpoint values are the ones WordPress reads from `settings.viewport` to
 * size its own responsive block styles, so component CSS written with these
 * mixins changes at the same widths the editor does. The mixins themselves are
 * SCSS-only — nothing in WordPress consumes them.
 *
 * Each breakpoint yields a complementary pair: `below-x` uses `<=` and `above-x`
 * uses `>`, so no viewport width ever matches both. That is what removes the need
 * for the usual `- 0.02px` offset between a hand-written max/min pair.
 *
 * Mixin names are deliberately unprefixed: the file is meant to be `@use`d, which
 * namespaces them (`@include ds.above-tablet`).
 *
 * Returns an empty array when no viewport tokens are defined.
 */
export function buildViewportMixins(prefix: string, group: TokenGroup | undefined): string[] {
  if (!group) return [];

  const mobile = group.mobile ? `$${prefix}-viewport-mobile` : null;
  const tablet = group.tablet ? `$${prefix}-viewport-tablet` : null;
  if (!mobile && !tablet) return [];

  const lines: string[] = [
    '',
    '// Viewport media queries',
    '// Built from the settings.viewport breakpoints WordPress uses for responsive',
    '// block styles. Each below-/above- pair is an exact complement, so no viewport',
    '// width matches both.',
  ];

  const mixin = (name: string, condition: string) => {
    lines.push('');
    lines.push(`@mixin ${name} {`);
    lines.push(`  @media ${condition} {`);
    lines.push('    @content;');
    lines.push('  }');
    lines.push('}');
  };

  // A breakpoint that isn't configured simply contributes no pair.
  if (mobile) {
    mixin('below-mobile', `(width <= #{${mobile}})`);
    mixin('above-mobile', `(width > #{${mobile}})`);
  }

  if (tablet) {
    mixin('below-tablet', `(width <= #{${tablet}})`);
    mixin('above-tablet', `(width > #{${tablet}})`);
  }

  return lines;
}
